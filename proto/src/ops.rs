//! What each op is, as the schema's options say (`wire/chatkord/v1/options.proto`): an ask names the op that answers
//! it, a tell is answered by nothing, and the rest only the server sends. `gen/ops.rs` is written from those options
//! by `examples/ops.rs` (run by `scripts/gate/codegen.sh`), so no list here restates them.

use crate::chatkord_v1::wire_message::Body;

pub use crate::chatkord_v1::Sender;

/// An op a client sends and the server answers with `Reply` or a refusal; it holds a slot of the asks in flight
/// until answered.
pub trait Ask: Into<Body> {
    /// The op that answers it.
    type Reply: Reply;
}

/// An op that answers an ask.
pub trait Reply: Sized {
    /// The op `body` carries, when it is this one.
    fn of(body: Body) -> Option<Self>;
}

/// An op a client sends that nothing answers; it holds no slot of the asks in flight.
pub trait Tell: Into<Body> {}

#[cfg(not(feature = "codegen"))]
include!("../gen/ops.rs");

/// Whether `kind` is a tell: a client sends it and nothing answers it, its refusal included. A heartbeat, which either
/// end sends and the other echoes, is not one.
#[cfg(not(feature = "codegen"))]
pub const fn is_tell(kind: Kind) -> bool {
    matches!(sent_by(kind), Sender::Client) && reply_of(kind).is_none()
}

/// `gen/ops.rs` as the schema's options make it.
#[cfg(feature = "codegen")]
pub fn render() -> String {
    use crate::schema::{SCHEMA, Shape};
    use std::fmt::Write as _;

    let schema = &*SCHEMA;
    let wire = &schema.messages[schema.wire];
    let mut ops: Vec<(u32, String, &crate::schema::Described)> = wire
        .fields
        .iter()
        .filter_map(|(&number, field)| match field.shape {
            Shape::Message(Some(held)) if field.oneof.is_some() => {
                Some((number, variant(&field.name), &schema.messages[held]))
            }
            _ => None,
        })
        .collect();
    ops.sort_by_key(|(number, ..)| *number);
    let variant_of = |name: &str| {
        let full = format!(".chatkord.v1.{name}");
        ops.iter().find(|(_, _, message)| message.name == full).map(|(_, variant, _)| variant.clone())
    };
    let short = |message: &crate::schema::Described| message.name.rsplit('.').next().unwrap_or_default().to_string();
    let sender = |message: &crate::schema::Described| match message.sent_by {
        Some(1) => "Client",
        Some(2) => "Server",
        Some(3) => "Either",
        _ => "Unspecified",
    };
    let mut out = String::from(
        "// @generated by `cargo run --features codegen --example ops` in proto/, from wire/'s options. Not edited.\n\n\
         use crate::chatkord_v1::wire_message::Kind;\n\n",
    );
    out.push_str("/// Who sends an op of `kind`.\npub const fn sent_by(kind: Kind) -> Sender {\n    match kind {\n");
    for (_, variant, message) in &ops {
        let _ = writeln!(out, "        Kind::{variant} => Sender::{},", sender(message));
    }
    out.push_str("    }\n}\n\n");
    out.push_str(
        "/// The op that answers an ask of `kind`; none for an op that is no ask.\npub const fn reply_of(kind: Kind) -> \
         Option<Kind> {\n    match kind {\n",
    );
    for (_, variant, message) in &ops {
        let reply = message.reply.as_deref().and_then(variant_of);
        let _ = match reply {
            Some(reply) => writeln!(out, "        Kind::{variant} => Some(Kind::{reply}),"),
            None => writeln!(out, "        Kind::{variant} => None,"),
        };
    }
    out.push_str("    }\n}\n");
    out.push_str(&offered(&schema.enums));
    let mut replies = std::collections::BTreeSet::new();
    for (_, variant, message) in &ops {
        let name = short(message);
        let sent = matches!(message.sent_by, Some(1 | 3));
        if sent {
            let _ = write!(
                out,
                "\nimpl From<crate::chatkord_v1::{name}> for Body {{\n    fn from(op: crate::chatkord_v1::{name}) -> \
                 Self {{\n        Body::{variant}(op)\n    }}\n}}\n"
            );
        }
        match message.reply.as_deref() {
            Some(reply) if sent => {
                let _ = write!(
                    out,
                    "\nimpl Ask for crate::chatkord_v1::{name} {{\n    type Reply = crate::chatkord_v1::{reply};\n}}\n"
                );
                replies.insert(reply.to_string());
            }
            None if sent => {
                let _ = write!(out, "\nimpl Tell for crate::chatkord_v1::{name} {{}}\n");
            }
            _ => {}
        }
    }
    for reply in replies {
        if let Some(variant) = variant_of(&reply) {
            let _ = write!(
                out,
                "\nimpl Reply for crate::chatkord_v1::{reply} {{\n    fn of(body: Body) -> Option<Self> {{\n        \
                 if let Body::{variant}(op) = body {{ Some(op) }} else {{ None }}\n    }}\n}}\n"
            );
        }
    }
    out
}

/// `Feature::OFFERED`: every feature of the schema but `UNSPECIFIED`, so a server that offers the features of its
/// protocol's minors names none by hand.
#[cfg(feature = "codegen")]
fn offered(enums: &[(String, Vec<String>)]) -> String {
    let features =
        enums.iter().find(|(name, _)| name == "Feature").map(|(_, values)| values.as_slice()).unwrap_or_default();
    let variants: Vec<String> = features
        .iter()
        .filter_map(|value| value.strip_prefix("FEATURE_"))
        .filter(|value| *value != "UNSPECIFIED")
        .map(|value| variant(&value.to_ascii_lowercase()))
        .collect();
    let named: Vec<String> = variants.iter().map(|variant| format!("crate::chatkord_v1::Feature::{variant}")).collect();
    format!(
        "\nimpl crate::chatkord_v1::Feature {{\n    /// Every feature of this protocol, which a server that serves it all offers in its greeting.\n    \
         pub const OFFERED: [crate::chatkord_v1::Feature; {}] = [{}];\n}}\n",
        named.len(),
        named.join(", ")
    )
}

/// A oneof field's name as prost names its variant: `channels_list` is `ChannelsList`.
#[cfg(feature = "codegen")]
fn variant(field: &str) -> String {
    field
        .split('_')
        .map(|part| {
            let mut letters = part.chars();
            letters.next().map(|first| first.to_ascii_uppercase().to_string() + letters.as_str()).unwrap_or_default()
        })
        .collect()
}

#[cfg(all(test, not(feature = "codegen")))]
mod tests {
    use super::{Sender, is_tell, reply_of, sent_by};
    use crate::chatkord_v1::wire_message::Kind;
    use crate::envelope::every_op;

    #[test]
    fn every_op_says_who_sends_it_and_an_ask_is_answered_by_an_op_the_server_sends() {
        let ops = every_op();
        assert!(ops.len() > 50, "{} ops", ops.len());
        for op in &ops {
            let kind = Kind::from(op);
            assert_ne!(sent_by(kind), Sender::Unspecified, "{kind:?} says no sender");
            if let Some(reply) = reply_of(kind) {
                assert_ne!(sent_by(kind), Sender::Server, "{kind:?} is the server's and an ask");
                assert_eq!(sent_by(reply), Sender::Server, "{kind:?} is answered by {reply:?}, which a client sends");
            }
        }
    }

    #[test]
    fn a_tell_is_a_client_op_nothing_answers_and_a_heartbeat_is_none() {
        assert!(is_tell(Kind::Typing));
        assert!(!is_tell(Kind::Heartbeat), "echoed by the other end");
        assert!(!is_tell(Kind::Close));
        assert!(!is_tell(Kind::SendMessage));
    }
}
